"""M1 图表定义：每张图一条记录，kind=ir 走 fireworks 渲染器，kind=uml 走本仓库的 UML 生成器。

事实来源：src/mini_harness 的真实模块、签名与 openspec/specs 的规格条款。
M1 未实现的东西（工具实现、窗口预算、审批、HTTP 服务）一律用 async/虚线流标出，不画成已存在。
"""

from __future__ import annotations

from typing import Any

WIDTH = 1200
HEIGHT = 700


def ir(**data: Any) -> dict[str, Any]:
    base: dict[str, Any] = {
        "schema_version": 1,
        "style": 3,
        "quality_profile": "standard",
        "text_policy": "report",
        "width": WIDTH,
        "height": HEIGHT,
        "legend_orientation": "horizontal",
        "legend": [
            {"flow": "control", "label": "控制流"},
            {"flow": "read", "label": "读取 / 请求"},
            {"flow": "write", "label": "写入 / 追加"},
            {"flow": "data", "label": "数据流"},
            {"flow": "async", "label": "M1 未实现"},
        ],
    }
    base.update(data)
    return base


FIGURES: list[dict[str, Any]] = []


def add(
    fid: str,
    group: str,
    title: str,
    subtitle: str,
    kind: str,
    template: str,
    payload: dict[str, Any],
) -> None:
    entry = {
        "id": fid,
        "group": group,
        "title": title,
        "subtitle": subtitle,
        "kind": kind,
        "template": template,
    }
    if kind == "ir":
        entry["ir"] = ir(template_type=template, title=title, subtitle=subtitle, **payload)
    else:
        entry.update(payload)
    FIGURES.append(entry)


